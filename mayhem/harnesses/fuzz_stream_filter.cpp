/*
 * fuzz_stream_filter.cpp — the :82 CAN stream's query-string filter parser
 * (esp32/.firmware/http_can_stream.cpp): url_decode, parse_filter, parse_bus_filter and
 * configure_filter_from_path, which read "?ids=…&bus=…&meta=…" from the request line of any
 * client web_stream_access() admits.
 *
 * The functions are static in an Arduino/FreeRTOS translation unit, so build.sh cuts them out of
 * upstream's file unchanged (with the globals and limit they use) into
 * mayhem/out/gen/http_can_stream_filter.inc, and this harness includes that. The entry point is
 * configure_filter_from_path(), the call accept_client() makes on the request path.
 *
 * Input: the request path, as parse_request_path() copies it into accept_client()'s
 * char path[256]: 1..255 bytes plus a NUL. It is handed over in an exact-size heap buffer, so any
 * read or write past the terminator is reported. Each input stands alone: configure_filter_from_path
 * resets the filter state on every call, and only g_filter_ids[0..g_filter_count) is ever read.
 */
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "can_driver.h"  // CanBusId (esp32/.firmware)

#include "http_can_stream_filter.inc"  // generated by build.sh from upstream's file

extern "C" int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
    // parse_request_path() answers 400 for an empty path (path_end <= path_start) and for one of
    // path_len (256) bytes or more, so configure_filter_from_path() never sees either.
    if (size == 0 || size >= 256) return -1;

    char *path = (char *)malloc(size + 1);
    memcpy(path, data, size);
    path[size] = '\0';
    bool ok = configure_filter_from_path(path);
    free(path);

    // What upstream's parser promises when it accepts a filter: at most
    // HTTP_CAN_STREAM_MAX_FILTER_IDS distinct 29-bit ids, a valid bus.
    if (g_filter_count > HTTP_CAN_STREAM_MAX_FILTER_IDS) abort();
    if (ok) {
        if (g_bus_filter != CAN_BUS_PRIMARY && g_bus_filter != CAN_BUS_SECONDARY) abort();
        for (uint8_t i = 0; i < g_filter_count; i++) {
            if (g_filter_ids[i] > 0x1FFFFFFFu) abort();
            if (!filter_matches(g_filter_ids[i])) abort();
            for (uint8_t j = (uint8_t)(i + 1u); j < g_filter_count; j++)
                if (g_filter_ids[i] == g_filter_ids[j]) abort();
        }
    }
    return 0;
}
